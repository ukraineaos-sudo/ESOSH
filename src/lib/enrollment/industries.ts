export function isEnrollmentIndustryId(value: string): value is EnrollmentIndustryId {
  return (ENROLLMENT_INDUSTRY_IDS as readonly string[]).includes(value);
}

/** RU: Підпис галузі для локалі. EN: Industry label for locale. */
export function industryLabel(id: EnrollmentIndustryId, locale: AppLocale): string {
  return INDUSTRY_LABELS[id][locale] || INDUSTRY_LABELS[id].en;
}

/**
 * RU: Рядок галузі для збереження в заявці/профілі.
 * EN: Human-readable industry string for application/profile storage.
 */
export function formatIndustryForStorage(
  ids: EnrollmentIndustryId[],
  locale: AppLocale,
  otherText?: string,
): string {
  const parts = ids
    .filter((id) => id !== "other")
    .map((id) => industryLabel(id, locale));
  if (ids.includes("other")) {
    const trimmed = otherText?.trim();
    parts.push(trimmed ? `${industryLabel("other", locale)}: ${trimmed}` : industryLabel("other", locale));
  }
  return parts.join("; ");
}
